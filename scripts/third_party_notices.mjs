#!/usr/bin/env node
// Generate THIRD_PARTY_NOTICES.md (Lumen Pro P0; DECISIONS D-01).
//
//   node scripts/third_party_notices.mjs           write the file
//   node scripts/third_party_notices.mjs --check   exit 1 if it is out of date
//
// Sources: the firmware components below (pinned in src/idf_component.yml or
// vendored), webui production dependencies and their transitive production
// dependencies (licence read from node_modules), gateway/go.mod modules
// (licence must be listed in GO_LICENSES, so a new module forces a review).
// Fails when a licence is missing or not on the allowlist for closed-source
// commercial use.

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const ALLOWED = new Set(["MIT", "ISC", "Apache-2.0", "BSD-2-Clause", "BSD-3-Clause", "0BSD", "Zlib",
  "EPL-2.0 OR EDL-1.0", "MIT OR Apache-2.0", "Apache-2.0 OR MIT", "BlueOak-1.0.0", "CC0-1.0", "Unlicense"]);

const FIRMWARE = [
  { name: "ESP-IDF", version: "6.1.0", license: "Apache-2.0", url: "https://github.com/espressif/esp-idf", note: "includes FreeRTOS (MIT), lwIP (BSD-3-Clause), mbedTLS (Apache-2.0)" },
  { name: "espressif/mqtt (esp-mqtt)", version: "1.1.0", license: "Apache-2.0", url: "https://github.com/espressif/esp-mqtt" },
  { name: "espressif/mdns", version: "1.15.1", license: "Apache-2.0", url: "https://github.com/espressif/esp-protocols" },
  { name: "joltwallet/littlefs (esp_littlefs)", version: "1.23.3", license: "MIT", url: "https://github.com/joltwallet/esp_littlefs", note: "bundles littlefs (BSD-3-Clause)" },
  { name: "cJSON (vendored, src/core/cJSON.*)", version: "vendored", license: "MIT", url: "https://github.com/DaveGamble/cJSON" },
  { name: "Lucide icons (logo, web UI)", version: "—", license: "ISC", url: "https://lucide.dev/license" },
];
// Licences of Go modules, keyed by module path. Add an entry when go.mod gains one.
const GO_LICENSES = {
  "github.com/eclipse/paho.golang": "EPL-2.0 OR EDL-1.0",
  "github.com/coder/websocket": "ISC",
  "github.com/grandcat/zeroconf": "MIT",
  "github.com/miekg/dns": "BSD-3-Clause",
  "github.com/cenkalti/backoff/v4": "MIT",
  "github.com/BurntSushi/toml": "MIT",
  "golang.org/x/net": "BSD-3-Clause",
  "golang.org/x/sys": "BSD-3-Clause",
  "golang.org/x/sync": "BSD-3-Clause",
};

const problems = [];

function npmTree(dir) {
  const seen = new Map();
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  const queue = Object.keys(pkg.dependencies ?? {});
  while (queue.length) {
    const name = queue.shift();
    if (seen.has(name)) continue;
    const p = join(dir, "node_modules", name, "package.json");
    if (!existsSync(p)) { problems.push(`webui: ${name} not installed (run npm ci in webui/)`); continue; }
    const m = JSON.parse(readFileSync(p, "utf8"));
    const license = typeof m.license === "string" ? m.license : m.license?.type ?? "UNKNOWN";
    seen.set(name, { name, version: m.version, license, url: m.homepage ?? "" });
    for (const d of Object.keys(m.dependencies ?? {})) queue.push(d);
  }
  return [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
}

function goModules() {
  const p = join(root, "gateway", "go.mod");
  if (!existsSync(p)) return [];
  const mods = [];
  const text = readFileSync(p, "utf8");
  const re = /^\s*(?:require\s+)?([a-z0-9.\-]+\.[a-z]+\/[^\s]+)\s+(v[^\s]+)(\s*\/\/ indirect)?\s*$/gm;
  for (const [, name, version] of text.matchAll(re)) {
    const license = GO_LICENSES[name] ?? "UNKNOWN";
    mods.push({ name, version, license, url: `https://pkg.go.dev/${name}` });
  }
  return mods.sort((a, b) => a.name.localeCompare(b.name));
}

function check(section, items) {
  for (const i of items) if (!ALLOWED.has(i.license)) problems.push(`${section}: ${i.name} has licence "${i.license}" (not on the allowlist; review before use)`);
}

const web = npmTree(join(root, "webui"));
const go = goModules();
check("firmware", FIRMWARE);
check("webui", web);
check("gateway", go);

const row = (i) => `| ${i.name} | ${i.version} | ${i.license} | ${i.url}${i.note ? ` (${i.note})` : ""} |`;
const table = (items) => ["| Component | Version | Licence | Source |", "|---|---|---|---|", ...items.map(row)].join("\n");
const out = `# Third-party notices

Lumen Pro is proprietary (see LICENSE). It includes the third-party
components below, each under its own licence. Generated by
\`node scripts/third_party_notices.mjs\`; do not edit by hand. Full licence
texts ship with each component (ESP-IDF tree, \`node_modules/*/LICENSE\`, Go
module cache) and are bundled into release packages (P11).

## Controller firmware

${table(FIRMWARE)}

## Controller web UI (production dependencies, including transitive)

${table(web)}

## Lumen Gateway (Go modules)

${go.length ? table(go) : "No third-party modules yet (standard library only)."}

## Lumen Cloud and mobile app

Added when \`cloud/\` (P1) and \`mobile/\` (P7) gain dependencies.
`;

if (problems.length) {
  for (const p of problems) console.error(`  FAIL ${p}`);
  process.exit(1);
}
const target = join(root, "THIRD_PARTY_NOTICES.md");
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) {
    console.error("THIRD_PARTY_NOTICES.md is out of date: run node scripts/third_party_notices.mjs");
    process.exit(1);
  }
  console.log("third-party notices up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote THIRD_PARTY_NOTICES.md (${FIRMWARE.length} firmware, ${web.length} web UI, ${go.length} Go)`);
}
